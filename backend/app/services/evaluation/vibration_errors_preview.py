"""Vibration error preview image generator.

Produces a 1920 × 1080 static PNG that mirrors the visual style of the
angle_errors_preview.png generated by ``angle_errors._generate_angle_errors_preview()``:

Layers (bottom → top)
---------------------
1. Black background
2. Green dots — YOLO-detected scissors positions (one dot per detected frame)
3. Amber dots — scissors positions that fall inside a vibration error window
4. Amber dotted connector lines between consecutive error peak locations
5. Amber circle outlines + numbered labels at each vibration error peak location
6. Timeline bar (bottom 20 px): grey / green / amber segments + 1-second ticks

The amber/orange colour (BGR 0, 165, 255) matches the accent colour already used
throughout visualization.py.

Usage
-----
    from app.services.evaluation.vibration_errors_preview import (
        generate_vibration_errors_preview,
    )

    generate_vibration_errors_preview(
        preview_path   = "/path/to/vibration/vibration_errors_preview.png",
        vibration_errors = vibration_errors,   # list from detect_vibration_errors()
        yolo_roi_data  = yolo_roi_data,         # all_detections from run_shared_yolo()
        fps            = 30.0,
        total_frames   = 900,
    )
"""
from __future__ import annotations

import math
from pathlib import Path
from typing import Any


# Amber/orange accent colour (BGR) — same shade used in visualization.py
_AMBER = (0, 165, 255)

# Dot + circle dimensions — mirror angle_errors_preview.py
_DETECTION_DOT_RADIUS = 3
_ERROR_DOT_RADIUS      = 4
_ERROR_CIRCLE_RADIUS   = 80

# Timeline strip height (pixels) — same as angle_errors_preview.py
_TIMELINE_H = 20


# ── Internal dashed-line helper (copied from visualization.py) ────────────────

def _draw_dashed_segment(
    img: Any,
    p1: tuple[float, float],
    p2: tuple[float, float],
    color: tuple[int, int, int],
    thickness: int,
    dash: int = 12,
    gap: int = 8,
) -> None:
    """Draw a dashed line segment between p1 and p2 onto img."""
    import cv2  # noqa: PLC0415

    x1, y1 = float(p1[0]), float(p1[1])
    x2, y2 = float(p2[0]), float(p2[1])
    length = math.hypot(x2 - x1, y2 - y1)
    if length < 1:
        return
    ux, uy = (x2 - x1) / length, (y2 - y1) / length
    pos, drawing = 0.0, True
    while pos < length:
        seg = dash if drawing else gap
        end = min(pos + seg, length)
        if drawing:
            cv2.line(
                img,
                (int(round(x1 + ux * pos)), int(round(y1 + uy * pos))),
                (int(round(x1 + ux * end)), int(round(y1 + uy * end))),
                color, thickness, cv2.LINE_AA,
            )
        pos = end
        drawing = not drawing


# ── Public API ────────────────────────────────────────────────────────────────

def generate_vibration_errors_preview(
    preview_path: str,
    vibration_errors: list[dict],
    yolo_roi_data: list[dict],
    fps: float,
    total_frames: int | None = None,
) -> None:
    """Render a 1920 × 1080 summary image for the detected vibration errors.

    Parameters
    ----------
    preview_path:
        Absolute path where the PNG will be saved.
    vibration_errors:
        List of error dicts returned by ``detect_vibration_errors()``.
        Each must have ``peak_location``, ``timestamp_start_sec``,
        ``timestamp_end_sec``, ``frame_start``, ``frame_end``.
    yolo_roi_data:
        The ``all_detections`` list from ``run_shared_yolo()``.  Used to
        draw scissors positions and to derive total video duration.
    fps:
        Video frames per second.  Used to convert frame indices → seconds.
    total_frames:
        Total number of frames in the video.  When provided, the timeline
        is scaled to this length rather than the last YOLO detection frame.
    """
    try:
        import cv2          # noqa: PLC0415
        import numpy as np  # noqa: PLC0415
    except ImportError:
        print("[vibration_preview] WARNING: opencv-python not available — skipping preview")
        return

    W, H = 1920, 1080
    TIMELINE_Y = H - _TIMELINE_H

    canvas: Any = np.zeros((H, W, 3), dtype=np.uint8)

    # ── Determine video duration from available data ──────────────────────────
    fps_safe = max(float(fps), 1e-6)

    if total_frames is not None and total_frames > 0:
        max_ts = (total_frames - 1) / fps_safe
    elif yolo_roi_data:
        max_fi = max((int(d.get("frame_index", 0)) for d in yolo_roi_data), default=0)
        max_ts = max(max_fi / fps_safe, 1.0)
    else:
        max_ts = 1.0

    # ── Build set of frame indices that belong to any vibration error ─────────
    error_frame_set: set[int] = set()
    for ev in vibration_errors:
        for fi in range(int(ev.get("frame_start", 0)), int(ev.get("frame_end", 0)) + 1):
            error_frame_set.add(fi)

    # ── 1. Green dots — all detected scissors positions ───────────────────────
    for det in yolo_roi_data:
        if not det.get("detected", False):
            continue
        center = det.get("bbox_center")
        if not center or len(center) < 2:
            continue
        pt = (int(round(float(center[0]))), int(round(float(center[1]))))
        cv2.circle(canvas, pt, _DETECTION_DOT_RADIUS, (0, 200, 60), -1)

    # ── 2. Amber dots — scissors inside a vibration error window ─────────────
    for det in yolo_roi_data:
        fi = int(det.get("frame_index", -1))
        if fi not in error_frame_set:
            continue
        if not det.get("detected", False):
            continue
        center = det.get("bbox_center")
        if not center or len(center) < 2:
            continue
        pt = (int(round(float(center[0]))), int(round(float(center[1]))))
        cv2.circle(canvas, pt, _ERROR_DOT_RADIUS, _AMBER, -1)

    # ── 3. Amber dotted connector lines between consecutive error peaks ────────
    peak_pts: list[tuple[int, int]] = []
    for ev in vibration_errors:
        loc = ev.get("peak_location") or {}
        px = loc.get("x")
        py = loc.get("y")
        if px is not None and py is not None:
            peak_pts.append((int(round(float(px))), int(round(float(py)))))

    for i in range(len(peak_pts) - 1):
        _draw_dashed_segment(canvas, peak_pts[i], peak_pts[i + 1], _AMBER, 2, dash=14, gap=8)

    # ── 4. Amber circle outlines + numbered labels ─────────────────────────────
    font       = cv2.FONT_HERSHEY_SIMPLEX
    font_scale = 0.75
    for ev_idx, ev in enumerate(vibration_errors, start=1):
        loc = ev.get("peak_location") or {}
        px  = loc.get("x")
        py  = loc.get("y")
        if px is None or py is None:
            continue
        cx, cy = int(round(float(px))), int(round(float(py)))

        # Use sequential index — error_id may still be None before merge_errors runs
        display_id = ev.get("error_id") if ev.get("error_id") is not None else ev_idx

        # Build a suffix from the most useful available field: severity → freq → nothing
        severity = ev.get("severity") or ""
        freq     = ev.get("dominant_freq_hz")
        if severity:
            suffix = f"  {severity}"
        elif freq is not None:
            suffix = f"  {float(freq):.1f}Hz"
        else:
            suffix = ""

        label = f"VIBRATION ERROR {display_id}{suffix}"

        # Amber circle outline
        cv2.circle(canvas, (cx, cy), _ERROR_CIRCLE_RADIUS, _AMBER, 2, cv2.LINE_AA)

        # White outline then amber fill for the label — same two-pass technique
        # as the angle preview
        text_x = cx - _ERROR_CIRCLE_RADIUS
        text_y = cy - _ERROR_CIRCLE_RADIUS - 8
        cv2.putText(canvas, label, (text_x, text_y), font, font_scale, (255, 255, 255), 4, cv2.LINE_AA)
        cv2.putText(canvas, label, (text_x, text_y), font, font_scale, _AMBER,          2, cv2.LINE_AA)

    # ── 5. Timeline bar ────────────────────────────────────────────────────────
    # Dark background strip
    cv2.rectangle(canvas, (0, TIMELINE_Y), (W, H), (30, 30, 30), -1)

    # Per-frame colour: amber if in error window, green if detected, grey otherwise
    for det in yolo_roi_data:
        fi = int(det.get("frame_index", 0))
        ts = fi / fps_safe
        x  = int(ts / max_ts * (W - 1)) if max_ts > 0 else 0
        x  = max(0, min(W - 1, x))
        if fi in error_frame_set:
            col = _AMBER
        elif det.get("detected", False):
            col = (0, 150, 50)    # green
        else:
            col = (90, 90, 90)    # grey
        cv2.line(canvas, (x, TIMELINE_Y), (x, H - 1), col, 1)

    # Solid amber bars for each vibration event time range (drawn on top)
    for ev in vibration_errors:
        ts_start = float(ev.get("timestamp_start_sec", 0.0))
        ts_end   = float(ev.get("timestamp_end_sec", ts_start))
        x1 = max(0, int(ts_start / max_ts * (W - 1)))
        x2 = min(W - 1, int(ts_end   / max_ts * (W - 1)))
        if x2 >= x1:
            cv2.rectangle(canvas, (x1, TIMELINE_Y), (x2, H - 1), _AMBER, -1)

    # White tick marks every 1 second
    t_sec = 1.0
    while t_sec <= max_ts:
        tx = int(t_sec / max_ts * (W - 1))
        cv2.line(canvas, (tx, TIMELINE_Y), (tx, H - 1), (255, 255, 255), 1)
        cv2.putText(
            canvas,
            f"{int(t_sec)}s",
            (tx + 2, H - 4),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.35,
            (200, 200, 200),
            1,
            cv2.LINE_AA,
        )
        t_sec += 1.0

    # ── Save ──────────────────────────────────────────────────────────────────
    Path(preview_path).parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(preview_path, canvas)
    print(f"[vibration_preview] Preview saved: {preview_path}")
